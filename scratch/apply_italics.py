# Database identifiers that don't have underscores but are database tables/columns
DB_WORDS = [
    'users',
    'supplier',
]

ALL_WORDS = PHRASES + SINGLE_WORDS + DB_WORDS
# Sort by length descending
ALL_WORDS = sorted(list(set(ALL_WORDS)), key=lambda x: len(x), reverse=True)

# Build regex for words + any underscored database identifier (e.g. produk_induk, id_user, etc.)
escaped_words = [re.escape(w) for w in ALL_WORDS]
word_pattern = r'\b(?:' + '|'.join(escaped_words) + r')\b'
# Also match database identifiers with underscores like [a-z0-9]+_[a-z0-9_]+
db_pattern = r'\b[a-z][a-z0-9]*_[a-z0-9_]+\b'

master_pattern = re.compile(f'({word_pattern}|{db_pattern})')

# Special pattern for "tabel penjualan" -> "tabel <i>penjualan</i>"
tabel_penjualan_pattern = re.compile(r'\btabel\s+penjualan\b', re.IGNORECASE)

def transform_text_node(text):
    # First handle tabel penjualan -> tabel <i>penjualan</i>
    text = tabel_penjualan_pattern.sub('tabel <i>penjualan</i>', text)
    # Apply master pattern
    text = master_pattern.sub(lambda m: f'<i>{m.group(0)}</i>', text)
    return text

print('Master pattern compiled successfully!')
